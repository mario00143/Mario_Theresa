export interface SeedTasksResult {
  tasks: Task[];
  idByKey: Map<string, string>;
}

export function buildSeedTasks(): SeedTasksResult {
  const idByKey = new Map<string, string>();
  for (const seed of seeds) {
    idByKey.set(seed.key, generateSeedId('task', seed.key));
  }

  const tasks = seeds.map((seed) => {
    const createdAt = daysAgoISO(seed.createdDaysAgo ?? 30);
    const updatedAt = daysAgoISO(seed.updatedDaysAgo ?? seed.createdDaysAgo ?? 30);
    const dependencies = (seed.dependsOn ?? [])
      .map((key) => idByKey.get(key))
      .filter((id): id is string => Boolean(id));

    const task: Task = {
      id: idByKey.get(seed.key)!,
      title: seed.title,
      description: seed.description,
      event: seed.event,
      workstream: seed.workstream,
      owner: seed.owner,
      approver: seed.approver,
      status: seed.status,
      priority: seed.priority,
      startDate: seed.startDate,
      dueDate: seed.dueDate,
      dependencies,
      blockedReason: seed.blockedReason,
      nextAction: seed.nextAction,
      completionCriteria: seed.completionCriteria,
      completionNote: seed.completionNote,
      completionEvidence: seed.completionEvidence,
      tags: seed.tags ?? [],
      notes: seed.notes,
      subtasks: (seed.subtasks ?? []).map((s) => ({ ...s, id: generateId('subtask') })),
      createdAt,
      updatedAt,
    };
    return task;
  });

  return { tasks, idByKey };
}
